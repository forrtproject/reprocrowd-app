"""Code generation: a headless coding agent implements the TODO(LLM): markers of the master script.

Runs as a job. Before it starts, the package is committed to its git repository; afterwards the manifest is
synced with the files the agent created or changed, the changes are committed, and the remaining actionable
markers are counted.
"""
from __future__ import annotations

from typing import NamedTuple

from . import files, gitrepo, jobs
from .config import AgentProfile, expand_argv, settings
from .errors import ApiError, conflict
from .package import Package
from .schemas.jobs import CodegenResult, Job
from .scripts import Template, agent_prompt, current_template, mark_revised, outdated_claims, todo_status


def agent_profile(name: str | None) -> tuple[str, AgentProfile]:
    cfg = settings()
    name = name or cfg.agent_default_profile
    p = cfg.agent_profiles.get(name)
    if p is None:
        raise ApiError(400, "unknown_profile", f"no agent profile {name!r}; configured: {', '.join(cfg.agent_profiles)}")
    return name, p


class Plan(NamedTuple):
    name: str
    profile: AgentProfile
    template: Template
    tools: list[str]
    argv: list[str]
    prompt: str


def plan(pkg: Package, *, profile: str | None, allow_exec: bool, instructions: str, claim: str | None = None) -> Plan:
    """What a code-generation job would run; nothing is written."""
    name, prof = agent_profile(profile)
    tpl = current_template(pkg)
    if tpl is None:
        raise conflict("script_missing", "create the master script first (PUT …/script)")
    tools = prof.tools + (prof.exec_tools if allow_exec else [])
    argv = expand_argv(prof.argv, {"model": prof.model, "effort": prof.effort, "tools": ",".join(tools)})
    return Plan(name, prof, tpl, tools, argv, agent_prompt(pkg, tpl, instructions, claim))


def start(pkg: Package, *, profile: str | None, allow_exec: bool, instructions: str, claim: str | None = None) -> Job:
    name, prof, tpl, tools, argv, prompt = plan(pkg, profile=profile, allow_exec=allow_exec, instructions=instructions, claim=claim)
    jobs.ensure_idle(pkg)
    jid = jobs.new_id()
    revising = outdated_claims(pkg, tpl, claim)  # claim files the prompt asks to revise

    git_note, before = None, None
    if gitrepo.available():
        files.sync(pkg)
        before = gitrepo.commit(pkg, f"Before code generation ({jid})") or gitrepo.head(pkg)
    else:
        git_note = "git not found: changes are not committed"

    def finish(job: Job) -> CodegenResult:
        files.sync(pkg)
        if job.status == "succeeded":
            mark_revised(pkg, revising)
        after, changed = None, []
        if git_note is None:
            after = gitrepo.commit(pkg, f"Code generated by the agent ({jid}, {job.status}, exit {job.exit_code})")
            changed = gitrepo.changed_files(pkg, before, after)
        return CodegenResult(commit_before=before, commit_after=after, changed_files=changed, todo=todo_status(pkg, tpl), git_note=git_note)

    request = {"profile": name, "model": prof.model, "effort": prof.effort, "allow_exec": allow_exec, "instructions": instructions,
               "template": tpl.id, "tools": tools}
    if claim:
        request["claim"] = claim
    return jobs.start(pkg, jid=jid, type="codegen", argv=argv, stdin=prompt, timeout_s=prof.timeout_s, events_format=prof.events,
                      profile=name, request=request, finish=finish)
