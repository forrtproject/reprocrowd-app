def ready_package(client, pkg) -> Path:
    """A package with targets, actions and an R master script."""
    P = f"/v1/packages/{pkg}"
    client.post(P + "/fulltexts", json={"path": str(FIXTURES / "paper.tei.xml")})
    client.post(P + "/extractions", json={"method": "parse", "fulltext": "ft-paper-tei"})
    client.post(P + "/inputs", json={"path": str(FIXTURES / "data.csv"), "note": "reaction times"})
    client.post(P + "/targets", json={"type": "number", "description": "t", "expected": 2.31, "refs": [{"extraction": "ex-paper-tei", "id": "sec3.p1.s1"}]})
    client.post(P + "/actions", json={"kind": "analysis", "summary": "Run the t-test", "refs": [{"extraction": "ex-paper-tei", "id": "sec2.p1.s1"}],
                                      "inputs": ["in-data.csv"], "produces": ["T001"]})
    assert client.put(P + "/script", json={"template": "r"}).status_code == 201
    return Path(client.get(P).json()["path"])


def wait(client, pkg, jid, timeout=30):
    end = time.monotonic() + timeout
    while time.monotonic() < end:
        j = client.get(f"/v1/packages/{pkg}/jobs/{jid}").json()
        if j["status"] != "running" and j.get("finished_at"):
            return j
        time.sleep(0.05)
    raise TimeoutError(jid)


def test_todo_count_skips_header(client, pkg):
    root = ready_package(client, pkg)
    script = (root / "analysis.R").read_text()
    assert "Every TODO(LLM) block must be implemented" in script  # the explanatory header line
    st = client.get(f"/v1/packages/{pkg}/script").json()
    # L01, A01, OUT (+ the "load required packages" marker); the header is not counted
    lines = [line["text"] for line in st["todo"]["files"][0]["lines"]]
    assert st["todo"]["remaining"] == len(lines) == 4
    assert not any("Every" in t for t in lines)
    assert st["template"] == "r" and st["agent_prompt"] == "AGENT_PROMPT.md"
    prompt = (root / "AGENT_PROMPT.md").read_text()
    assert "inputs/data.csv: reaction times" in prompt and "Implement each step section of analysis.R" in prompt


def test_codegen_job(client, pkg):
    root = ready_package(client, pkg)
    P = f"/v1/packages/{pkg}"
    problem(client.post(P + "/jobs", json={"type": "codegen", "argv": ["sh"]}), 422, "request_invalid")
    problem(client.post(P + "/jobs", json={"type": "codegen", "profile": "nope"}), 400, "unknown_profile")
    r = client.post(P + "/jobs", json={"type": "codegen", "allow_exec": False, "instructions": "Use base R only."})
    assert r.status_code == 202, r.text
    job = r.json()
    assert r.headers["location"] == f"{P}/jobs/{job['id']}" and job["status"] == "running"
    assert "Bash(Rscript:*)" not in job["argv"][-1] and job["argv"][-1] == "Read,Write,Edit,Glob,Grep"
    job = wait(client, pkg, job["id"])
    assert job["status"] == "succeeded" and job["exit_code"] == 0, job

    res = job["result"]
    # the fake agent leaves the package-loading marker and the last step
    assert res["type"] == "codegen" and res["todo"]["remaining"] == 2
    assert [("packages" in t["text"], "OUT" in t["text"]) for t in res["todo"]["files"][0]["lines"]] == [(True, False), (False, True)]
    assert set(res["changed_files"]) >= {"analysis.R", "R/helpers.R", "install.R"}
    log = subprocess.run(["git", "log", "--format=%s"], cwd=root, capture_output=True, text=True).stdout.splitlines()
    assert log[0].startswith(f"Code generated by the agent ({job['id']}, succeeded") and log[1].startswith("Before code generation")
    stdin = (root / "jobs" / job["id"] / "stdin.txt").read_text()
    assert "Use base R only." in stdin and "TODO(LLM):" in stdin

    events = client.get(f"{P}/jobs/{job['id']}/events").json()
    kinds = [e["kind"] for e in events]
    assert kinds[0] == "start" and kinds[-1] == "result"
    assert {"text": "Read analysis.R", "kind": "tool_use"}.items() <= next(e for e in events if e["kind"] == "tool_use").items()
    assert any(e["kind"] == "tool_result" and e["is_error"] and "R not installed" in e["text"] for e in events)
    assert [e["seq"] for e in client.get(f"{P}/jobs/{job['id']}/events", params={"after": 5}).json()] == list(range(6, len(events) + 1))

    # SSE replays a finished job and ends with the job record
    with client.stream("GET", f"{P}/jobs/{job['id']}/events", headers={"Accept": "text/event-stream", "Last-Event-ID": "6"}) as s:
        body = "".join(s.iter_text())
    assert s.headers["content-type"].startswith("text/event-stream")
    assert "id: 6\n" not in body and "id: 7\n" in body and "event: end\n" in body
    end = json.loads(body.split("event: end\ndata: ")[1])
    assert end["status"] == "succeeded"

    # the manifest followed the agent: edited script refreshed, new files registered, package valid
    files = {f["path"]: f for f in client.get(f"{P}/files").json()}
    assert files["R/helpers.R"]["kind"] == "code" and files["analysis.R"]["kind"] == "script"
    assert client.get(f"{P}/validation").json()["valid"]
    # the implemented script is protected from being regenerated; "keep" updates everything else
    problem(client.put(f"{P}/script", json={"template": "r"}), 409, "script_modified")
    client.post(f"{P}/targets", json={"type": "number", "description": "new", "expected": 1, "unreferenced": True, "note": "n"})
    r = client.put(f"{P}/script", json={"template": "r", "on_modified": "keep"}).json()
    assert r["kept"] == ["analysis.R"] and "analysis.R" not in r["files"]
    assert "x <- read.csv" in (root / "analysis.R").read_text()
    assert [t["id"] for t in json.loads((root / "results_schema.json").read_text())["results"]] == ["T001", "T002"]


def test_codegen_live_stream_cancel_and_timeout(client, pkg):
    ready_package(client, pkg)
    P = f"/v1/packages/{pkg}"
    problem(client.delete(P + "/jobs/job-nope"), 404, "not_found")
    job = client.post(P + "/jobs", json={"type": "codegen", "profile": "slow"}).json()
    problem(client.post(P + "/jobs", json={"type": "codegen"}), 409, "job_running")
    problem(client.put(P + "/script", json={"template": "python"}), 409, "job_running")
    problem(client.post(f"/v1/packages/{pkg}:sync"), 409, "job_running")
    # live: the first events arrive while the agent still runs
    deadline = time.monotonic() + 10
    while len(client.get(f"{P}/jobs/{job['id']}/events").json()) < 3 and time.monotonic() < deadline:
        time.sleep(0.05)
    assert client.get(f"{P}/jobs/{job['id']}").json()["status"] == "running"
    assert client.delete(f"{P}/jobs/{job['id']}").status_code == 202
    job = wait(client, pkg, job["id"])
    assert job["status"] == "cancelled"
    problem(client.delete(f"{P}/jobs/{job['id']}"), 409, "job_finished")

    job = wait(client, pkg, client.post(P + "/jobs", json={"type": "codegen", "profile": "short"}).json()["id"])
    assert job["status"] == "timeout"
    job = wait(client, pkg, client.post(P + "/jobs", json={"type": "codegen", "profile": "fail"}).json()["id"])
    assert job["status"] == "failed" and job["exit_code"] == 2
    assert "agent crashed" in (Path(client.get(P).json()["path"]) / job["stderr"]).read_text()
    assert [j["status"] for j in client.get(P + "/jobs").json()] == ["cancelled", "timeout", "failed"]


def test_codegen_needs_script_and_interrupted_jobs(client, pkg, tmp_path):
    problem(client.post(f"/v1/packages/{pkg}/jobs", json={"type": "codegen"}), 409, "script_missing")
