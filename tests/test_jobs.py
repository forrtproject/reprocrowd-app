    (root / "jobs").mkdir()
    rec = {"id": "job-old-1", "type": "codegen", "status": "running", "argv": ["x"], "created_at": "2026-01-01T00:00:00Z",
           "stdout": "jobs/job-old-1/stdout.log", "stderr": "jobs/job-old-1/stderr.log", "events_format": "text"}
